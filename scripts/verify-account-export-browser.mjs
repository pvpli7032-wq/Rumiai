import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const base = process.env.TEST_BASE_URL;
assert(base && ['127.0.0.1', 'localhost'].includes(new URL(base).hostname), '须指定本机隔离服务 TEST_BASE_URL');
assert.equal(process.env.TEST_ISOLATED_DB, 'true', '该测试会创建账号，须确认隔离数据库');
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'zh-CN', acceptDownloads: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  assert.equal((await page.request.get(`${base}/api/users/me/export`)).status(), 401);
  const suffix = randomUUID().replaceAll('-', '').slice(0, 12);
  const registered = await page.request.post(`${base}/api/auth/register`, { data: { username: `export_ui_${suffix}`, email: `export_${suffix}@example.invalid`, password: `LocalOnly!${randomUUID()}` } });
  assert.equal(registered.status(), 201, await registered.text());
  const { user, token } = await registered.json();
  await page.goto(`${base}/login`);
  await page.evaluate(value => localStorage.setItem('xingban_token', value), token);
  await page.goto(`${base}/profile`);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出数据', exact: true }).click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'xingban-account-data.json');
  const output = path.resolve('artifacts/account-export');
  await mkdir(output, { recursive: true });
  const file = path.join(output, 'account-data.json');
  await download.saveAs(file);
  const raw = await readFile(file, 'utf8'), archive = JSON.parse(raw);
  assert.equal(archive.version, 2);
  assert.equal(archive.account.id, user.id);
  assert(Array.isArray(archive.reports) && Array.isArray(archive.aiCalls) && Array.isArray(archive.following));
  assert(!raw.includes('passwordHash') && !raw.includes('tokenVersion'));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.route('**/api/users/me/export', route => route.fulfill({ status: 500, json: { error: '测试导出失败' } }));
  await page.getByRole('button', { name: '导出数据', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '测试导出失败' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS 本人账号真实导出/下载 JSON v2、匿名拒绝、凭据排除、390px 布局、失败可见（仅失败 UI 使用模拟响应）');
} finally { await browser.close(); }

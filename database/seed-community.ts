async function main() {
  const owner = await db.user.upsert({
    where: { email: 'original-seed@example.invalid' },
    update: {},
    create: { username: '星伴原创角色', displayName: '星伴原创角色', email: 'original-seed@example.invalid', passwordHash: await bcrypt.hash(crypto.randomUUID(), 10), avatarUrl: '/brand/icon.svg' },
    select: { id: true },
  });
  for (const [index, [name, tagline, personality, greeting]] of personas.entries()) {
    const id = `xingban-original-${index + 6}`;
    await db.character.upsert({ where: { id }, update: {}, create: {
      id, name, tagline, personality,
      background: `这是为星伴内部测试创作的虚构角色。${name}在星河街经营自己的兴趣生活，与来访者交流${tagline}相关的见闻。角色背景为本项目 AI 辅助原创草稿，不引用已知影视、游戏或文学人物。`,
      greeting, avatarUrl: `/brand/persona-${index % 6}.svg`, creatorId: owner.id,
      isPublic: true, publicationRequested: true, reviewStatus: 'APPROVED',
      copyrightStatement: '星伴项目 AI 辅助原创内部测试稿；未有意引用现成作品。头像为本项目 SVG。此记录不替代人工权利核验，商业发布前须由项目方确认。',
      tags: 'Original,Community', scenario: `你来到星河街的工作空间，和${name}开始一次关于${tagline}的交流。`, relationshipStatus: '初识',
    } });
  }
  for (const [index, [name, description, tags]] of circles.entries()) {
    const id = `xingban-topic-${index}`;
    await db.circle.upsert({ where: { id }, update: {}, create: { id, name, description, tags, ownerId: owner.id, status: 'ACTIVE' } });
  }
  console.log(`原创内容种子完成：新增角色 ${personas.length} 位、圈子话题 ${circles.length} 个；重复运行不覆盖既有记录。`);
}

main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => db.$disconnect());

import test from 'node:test';
import assert from 'node:assert/strict';
import {createFixture} from '../helpers/sqlite-fixture.mjs';

test('admin account detail exposes membership assets and usage summary', async t => {
  const fixture = await createFixture();
  t.after(() => fixture.cleanup());
  const plan = await fixture.db.membershipPlan.update({where: {code: 'MONTHLY'}, data: {priceCents: 3000, isActive: true, benefitsJson: JSON.stringify([{key: 'DAILY_FREE_REPLIES', label: '每日免费回复', value: 5}])}});
  const order = await fixture.db.membershipOrder.create({data: {orderNo: 'ACCOUNT-ASSET-ORDER', userId: fixture.user.id, idempotencyKey: 'account-asset-order', planId: plan.id, amountCents: 3000, durationDays: 30, refundWindowHours: 24, usageChargePeriodHours: 24, benefitsJson: plan.benefitsJson, status: 'PAID', paidAt: new Date()}});
  await fixture.db.membershipGrant.create({data: {orderId: order.id, userId: fixture.user.id, startsAt: new Date(Date.now() - 1_000), expiresAt: new Date(Date.now() + 86_400_000), benefitsJson: plan.benefitsJson}});
  await fixture.db.membershipUsage.createMany({data: Array.from({length: 501}, (_, index) => ({orderId: order.id, userId: fixture.user.id, benefitCode: 'DAILY_FREE_REPLIES', quantity: 1, idempotencyKey: `account-asset-usage-${index}`}))});
  const {readManagedAccount} = await import('@rumiai/backend/modules/accounts/management-service');
  const detail = await readManagedAccount(fixture.admin.id, fixture.user.id);
  assert.equal(detail.assets.membership.current?.orderNo, order.orderNo);
  assert.equal(detail.assets.membership.orders[0]?.usage?.consumed, 501);
  assert.equal(detail.assets.finance.visible, true);
  const viewer = await fixture.db.user.create({data: {username: 'account-assets-viewer', email: 'account-assets-viewer@example.test', passwordHash: 'integration-only'}});
  const role = await fixture.db.adminRole.create({data: {code: 'ACCOUNT_ASSETS_VIEWER', name: '账户资产查看测试', permissions: {create: {permission: 'accounts.read'}}}});
  await fixture.db.adminOperator.create({data: {userId: viewer.id, enabled: true}});
  await fixture.db.adminRoleAssignment.create({data: {userId: viewer.id, roleId: role.id}});
  const restricted = await readManagedAccount(viewer.id, fixture.user.id);
  const restrictedOrder = restricted.assets.membership.orders[0];
  assert.equal(restricted.assets.finance.visible, false);
  assert.equal(restricted.assets.finance.ledger, null);
  assert.equal(restrictedOrder?.amountCents, null);
  assert.equal(restrictedOrder?.refund, null);
  assert.equal(restrictedOrder?.usage, null);

  // Reuse this fixture: backend Prisma is process-scoped.
  const {updateOwnProfile, readOwnProfile} = await import('@rumiai/backend/modules/accounts/profile-service');
  const {readManagedProfile, updateManagedProfile} = await import('@rumiai/backend/modules/accounts/admin-profile-service');
  await fixture.db.uploadAsset.create({data: {ownerId: fixture.admin.id, url: '/uploads/foreign-profile.png', mimeType: 'image/png', byteSize: 64}});
  await assert.rejects(() => updateOwnProfile(fixture.user.id, {avatarUrl: '/uploads/foreign-profile.png'}), /不属于/);
  await assert.rejects(() => updateOwnProfile(fixture.user.id, {avatarUrl: {url: '/brand/icon.svg'}}), /文本/);
  await assert.rejects(() => updateOwnProfile(fixture.user.id, {avatarUrl: 'javascript:alert(1)'}), /地址/);
  await assert.rejects(() => updateOwnProfile(fixture.user.id, {displayName: '名'.repeat(101)}), /1–100/);
  await fixture.db.uploadAsset.create({data: {ownerId: fixture.user.id, url: '/uploads/owned-profile.png', mimeType: 'image/png', byteSize: 64}});
  await updateOwnProfile(fixture.user.id, {displayName: '前台修改资料', avatarUrl: '/uploads/owned-profile.png'});
  const managed = await readManagedProfile(fixture.admin.id, fixture.user.id);
  assert.equal(managed.displayName, '前台修改资料');
  assert.equal(managed.avatarUrl, '/uploads/owned-profile.png');
  await updateManagedProfile(fixture.admin.id, fixture.user.id, {displayName: '后台修改资料', version: managed.accountVersion, reason: 'fixture profile round-trip'});
  const own = await readOwnProfile(fixture.user.id);
  assert.equal(own.displayName, '后台修改资料');
  assert.equal(own.avatarUrl, '/uploads/owned-profile.png');
  await updateOwnProfile(fixture.user.id, {avatarUrl: null});
  assert.equal((await readManagedProfile(fixture.admin.id, fixture.user.id)).avatarUrl, null, 'null explicitly clears an avatar');

  const {readOwnMembershipUsage, readMembershipCatalogue} = await import('@rumiai/backend/modules/memberships/service');
  const firstPage = await readOwnMembershipUsage(fixture.user.id, {orderNo: order.orderNo, limit: '2'});
  assert.equal(firstPage.items.length, 2);
  assert.equal(firstPage.summary.consumed, 501);
  assert.ok(firstPage.nextCursor);
  const secondPage = await readOwnMembershipUsage(fixture.user.id, {orderNo: order.orderNo, limit: '2', cursor: firstPage.nextCursor});
  assert.equal(secondPage.items.length, 2);
  assert.equal(new Set([...firstPage.items, ...secondPage.items].map(item => item.id)).size, 4, 'cursor pages must not overlap');
  assert.equal(firstPage.items[0].label, '每日免费回复', 'usage labels come from the order snapshot');
  assert.equal(firstPage.items[0].affectsRefund, true);
  await assert.rejects(() => readOwnMembershipUsage(fixture.admin.id, {orderNo: order.orderNo}), /不存在/);
  await assert.rejects(() => readOwnMembershipUsage(fixture.user.id, {orderNo: order.orderNo, cursor: 'not-a-cursor'}), /游标/);
  await assert.rejects(() => readOwnMembershipUsage(fixture.user.id, {orderNo: order.orderNo, limit: '101'}), /每页/);
  const {signToken} = await import('@rumiai/backend/infrastructure/auth/auth');
  const usageApi = await import('../../apps/api/src/app/api/me/membership/usage/route');
  const ownerToken = await signToken({userId: fixture.user.id, email: fixture.user.email, tokenVersion: 0});
  const otherToken = await signToken({userId: fixture.admin.id, email: fixture.admin.email, tokenVersion: 0});
  const usageUrl = 'http://fixture.test/api/me/membership/usage?orderNo=' + order.orderNo + '&limit=2';
  assert.equal((await usageApi.GET(new Request(usageUrl))).status, 401);
  assert.equal((await usageApi.GET(new Request(usageUrl, {headers: {authorization: 'Bearer ' + otherToken}}))).status, 404);
  const ownedUsageResponse = await usageApi.GET(new Request(usageUrl, {headers: {authorization: 'Bearer ' + ownerToken}}));
  assert.equal(ownedUsageResponse.status, 200);
  assert.equal((await ownedUsageResponse.json()).items.length, 2);

  const catalog = await readMembershipCatalogue();
  assert.ok(catalog.benefitDefinitions.every(item => item.unit && item.description && item.scope));
  assert.deepEqual(catalog.benefitDefinitions.map(item => item.key).sort(), ['CHARACTER_CREATE_LIMIT', 'CHAT_PRICE_MULTIPLIER', 'DAILY_FREE_REPLIES']);

  const {readCreatorCharacterQuota} = await import('@rumiai/backend/modules/characters/creator-service');
  await fixture.db.operationSetting.upsert({where: {key: 'content.character.maxOwned'}, update: {value: '2'}, create: {key: 'content.character.maxOwned', group: 'chat', value: '2', updatedBy: fixture.admin.id}});
  const {clearCache} = await import('@rumiai/backend/modules/settings/cache');
  clearCache();
  const publicQuota = await readCreatorCharacterQuota(fixture.user.id);
  assert.equal(publicQuota.publicLimit, 2);
  assert.equal(publicQuota.source, 'PUBLIC');
  await fixture.db.membershipGrant.update({where: {orderId: order.id}, data: {benefitsJson: JSON.stringify([{key: 'CHARACTER_CREATE_LIMIT', label: '角色上限', value: 3}])}});
  const memberQuota = await readCreatorCharacterQuota(fixture.user.id);
  assert.equal(memberQuota.effectiveLimit, 3);
  assert.equal(memberQuota.source, 'MEMBERSHIP');
  assert.equal(memberQuota.membershipOrderNo, order.orderNo);
  await fixture.db.operationSetting.update({where: {key: 'content.character.maxOwned'}, data: {value: '0'}});
  clearCache();
  const unlimitedQuota = await readCreatorCharacterQuota(fixture.user.id);
  assert.equal(unlimitedQuota.effectiveLimit, null);
  assert.equal(unlimitedQuota.remaining, null);
  assert.equal(unlimitedQuota.source, 'PUBLIC_UNLIMITED');
});

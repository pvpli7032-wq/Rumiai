import test from 'node:test';
import assert from 'node:assert/strict';
import {createFixture} from '../helpers/sqlite-fixture.mjs';
test('sharing requires explicit owned selections, freezes content, supports revoke and invalidates changed sources',async t=>{
 const f=await createFixture();t.after(()=>f.cleanup());
 const {previewConversationShare,createConversationShare,revokeConversationShare,readPublicConversationShare}=await import('@rumiai/backend/modules/conversations/share-service');
 const role=await f.db.character.create({data:{name:'share-test',personality:'fixture',background:'fixture',creatorId:f.user.id,isPublic:true,reviewStatus:'APPROVED'}});
 const conv=await f.db.conversation.create({data:{userId:f.user.id,characterId:role.id,title:"private conversation title",notes:"private note"}});
 const a=await f.db.message.create({data:{conversationId:conv.id,role:'USER',content:'selected text'}});
 assert.equal(await readPublicConversationShare(conv.id),null,'legacy conversation id is never a share');
 await assert.rejects(()=>createConversationShare(f.user.id,conv.id,{}));
 await assert.rejects(()=>createConversationShare(f.admin.id,conv.id,{confirmed:true,messageIds:[a.id]}));
 const foreign=await f.db.conversation.create({data:{userId:f.admin.id,characterId:role.id}});
 const secret=await f.db.message.create({data:{conversationId:foreign.id,role:'USER',content:'not public'}});
 await assert.rejects(()=>createConversationShare(f.user.id,conv.id,{confirmed:true,messageIds:[secret.id]}));
 const selection=async()=>{const preview=await previewConversationShare(f.user.id,conv.id);return {confirmed:true as const,messageIds:[a.id],messageVersions:Object.fromEntries(preview.messages.map(m=>[m.id,m.version]))};};
 const shared=await createConversationShare(f.user.id,conv.id,await selection());
 const view=await readPublicConversationShare(shared.id);
 assert.equal(view?.title,null);assert.ok(!JSON.stringify(view).includes("private note"));
 assert.deepEqual(view?.messages.map(m=>m.content),['selected text']);
 await f.db.message.create({data:{conversationId:conv.id,role:'ASSISTANT',content:'future private reply'}});
 assert.deepEqual((await readPublicConversationShare(shared.id))?.messages.map(m=>m.content),['selected text']);
 assert.equal((await previewConversationShare(f.user.id,conv.id)).shares.length,1);
 await assert.rejects(()=>revokeConversationShare(f.admin.id,conv.id,shared.id));
 await revokeConversationShare(f.user.id,conv.id,shared.id);
 assert.equal(await readPublicConversationShare(shared.id),null);
 await revokeConversationShare(f.user.id,conv.id,shared.id);
 const oldSelection=await selection();
 await f.db.message.update({where:{id:a.id},data:{content:'changed after preview'}});
 await assert.rejects(()=>createConversationShare(f.user.id,conv.id,oldSelection),/已变化/);
 const changed=await createConversationShare(f.user.id,conv.id,await selection());
 await f.db.message.update({where:{id:a.id},data:{content:'edited'}});
 assert.equal(await readPublicConversationShare(changed.id),null);
 const deleted=await createConversationShare(f.user.id,conv.id,await selection());
 await f.db.conversation.delete({where:{id:conv.id}});
 assert.equal(await readPublicConversationShare(deleted.id),null);
 assert.equal(await f.db.conversationShare.count({where:{conversationId:conv.id}}),0);
});

import {strict as assert} from 'node:assert';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
assert.ok(process.env.FRONTEND_REDESIGN_FIXTURE_MANIFEST,'FRONTEND_REDESIGN_FIXTURE_MANIFEST is required');
const manifest=JSON.parse(readFileSync(process.env.FRONTEND_REDESIGN_FIXTURE_MANIFEST,'utf8'));
const base=manifest.webBaseUrl||'http://127.0.0.1:3310';
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||'/usr/lib64/chromium-browser/headless_shell'});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
const page=await context.newPage();
try{
 await page.goto(base+'/login?next=/profile');
 await page.locator('#login-email').fill(manifest.login.email); await page.locator('#login-password').fill(manifest.login.password);
 const loginResponse=page.waitForResponse(response=>response.url().includes('/api/auth/login')&&response.request().method()==='POST');
 await page.getByRole('button',{name:'登录',exact:true}).click();
 assert.ok((await loginResponse).ok(),'fixture login must succeed');
 await page.waitForFunction(()=>Boolean(localStorage.getItem('xingban_token')));
 await page.goto(base+'/profile',{waitUntil:'networkidle'}); await page.getByRole('heading',{name:'每日签到',exact:true}).waitFor();
 await page.getByRole('button',{name:'编辑资料',exact:true}).click();
 await page.getByLabel('昵称').fill(manifest.expected.fixtureUserName);
 const put=page.waitForResponse(r=>r.url().includes('/api/users/me')&&r.request().method()==='PUT');
 await page.getByRole('button',{name:'保存资料',exact:true}).click(); assert.ok((await put).ok(),'profile PUT must succeed');
 await page.getByRole('heading',{name:'阅读设置',exact:true}).waitFor();
 const save=page.getByRole('button',{name:'保存设置',exact:true}); await save.click(); await save.waitFor({state:'visible'});
 await page.goto(base+'/verify-email'); await page.getByText('验证链接缺少令牌', {exact:false}).waitFor();
 await page.goto(base+'/reset-password'); await page.getByText('重置链接缺少令牌', {exact:false}).waitFor();
 await page.goto(base+'/activate-account'); await page.getByText('激活链接缺少令牌', {exact:false}).waitFor();
 await page.goto(base+'/forgot-password'); await page.getByRole('button',{name:'发送重置邮件',exact:true}).waitFor();
 await page.goto(base+'/profile');
 await page.getByRole('button',{name:/通知/}).click();
 await page.getByText(manifest.ids.notificationTitle,{exact:true}).waitFor();
 await page.route('**/api/me/notifications',route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":"synthetic notification write failure"}'}));
 await page.getByRole('button',{name:'全部标记已读',exact:true}).click();
 await page.waitForTimeout(100);
 assert.ok(await page.getByLabel('未读').count()>0,'503 must roll back the unread notification');
 await page.unroute('**/api/me/notifications');
 await page.goto(base+'/profile'); let closeWrites=0; page.on('request',request=>{if(request.url().includes('/api/users/me/close'))closeWrites+=1;});
 await page.getByText('注销账号',{exact:true}).click(); await page.getByText('注销账号',{exact:true}).click();
 assert.equal(closeWrites,0,'cancelling account closure must not write');
 console.log(JSON.stringify({status:'PASS',scope:'account',payment:{checkout:false,refunds:false,aiFees:false}}));
}finally{await context.close();await browser.close();}
